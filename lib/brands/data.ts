export type BrandContent = (typeof brandContent.brands)[number];
export type SystemContent = (typeof brandContent.systems)[number];

export function getBrand(slug: string) {
  return brandContent.brands.find((brand) => brand.slug === slug);
}

export function getSystem(brandSlug: string, systemSlug: string) {
  return brandContent.systems.find(
    (system) =>
      system.brandSlug === brandSlug &&
      system.slug === systemSlug,
  );
}

export function getBrandSystems(brandSlug: string) {
  return brandContent.systems.filter(
    (system) => system.brandSlug === brandSlug,
  );
}
